using System;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using MedLinkPortal.Attributes;

namespace MedLinkPortal.Models
{
    public enum VisaStatus
    {
        Submitted,          // Patient submitted request
        DocumentsUnderReview, // Admin reviewing documents
        InvitationIssued,   // Hospital invitation letter generated
        EmbassySubmitted,   // Patient submitted to embassy
        VisaApproved,       // Visa granted
        VisaRejected,       // Visa denied
        Cancelled
    }

    [Table("VisaApplications")]
    public class VisaApplication
    {
        [Key]
        public int Id { get; set; }

        /// <summary>Unique reference ID like MLVISA-2026-00001 for tracking</summary>
        [StringLength(30)]
        public string ReferenceId { get; set; } = string.Empty;

        [Required]
        public string UserId { get; set; } = string.Empty;

        // Linked to Medical Tourism Request (optional)
        public int? TourismRequestId { get; set; }
        [ForeignKey("TourismRequestId")]
        public virtual MedicalTourismRequest? TourismRequest { get; set; }

        // Applicant Details
        [Required]
        [Encrypted]
        public string FullName { get; set; } = string.Empty;

        [Required]
        public string Nationality { get; set; } = string.Empty;

        [Required]
        public string PassportNumber { get; set; } = string.Empty;

        public DateTime? PassportExpiry { get; set; }

        [Required]
        public string TreatmentType { get; set; } = string.Empty;

        public string? HospitalName { get; set; }   // Preferred or assigned hospital

        public DateTime? PlannedArrivalDate { get; set; }

        public string? MedicalReportsUrl { get; set; }

        public string? BankStatementUrl { get; set; }

        public string? PassportCopyUrl { get; set; }

        [Encrypted]
        public string? AdditionalNotes { get; set; }

        // Status & Tracking
        public VisaStatus Status { get; set; } = VisaStatus.Submitted;

        // Admin fields
        public string? AdminNotes { get; set; }

        public string? InvitationLetterUrl { get; set; }   // PDF invitation generated by admin

        public string? ProcessedBy { get; set; }

        public DateTime? ProcessedAt { get; set; }

        // Timestamps
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
        public DateTime? UpdatedAt { get; set; }
    }
}
